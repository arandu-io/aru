// QueryHeaderPrefix opens every file `aru model:build` writes beside an entity.
//
// It is the standard marker for generated Go -- editors refuse to edit the file
// and linters skip it -- and it is also how model:build recognises its own
// files: one whose entity is gone is removed only when it starts with this, so a
// file somebody wrote by hand is never deleted for having a similar name.
const QueryHeaderPrefix = "// Code generated by aru model:build from "

// QueryHeader is the first line of the file generated from source, the base
// name of the file declaring the entity.
func QueryHeader(source string) string {
	return QueryHeaderPrefix + source + ". DO NOT EDIT."
}

// GeneratedQuerySource reports whether content is a file model:build wrote, and
// which entity file it was written from.
func GeneratedQuerySource(content []byte) (string, bool) {
	line, _, _ := bufio.NewReader(bytes.NewReader(content)).ReadLine()
	rest, found := strings.CutPrefix(string(line), QueryHeaderPrefix)
	if !found {
		return "", false
	}
	source, found := strings.CutSuffix(rest, ". DO NOT EDIT.")
	return source, found && source != ""
}

// QuerySpec is what the query file of one entity is rendered from: the four
// names the file declares or calls, and whether the table soft deletes.
//
// It is deliberately less than a Module. `aru model:build` fills it from the
// struct and the table it finds in the source, where there is no field list
// and no specification, and the file it renders depends on nothing else -- so
// adding a column changes no generated byte.
type QuerySpec struct {
	// Package is the package clause of the entity's file: "models".
	Package string
	// Entity is the struct embedding model.Model: "PurchaseOrder".
	Entity string
	// Source is the base name of the file declaring Entity, named in the
	// header: "PurchaseOrder.go".
	Source string
	// Constructor is the function a query starts from: "PurchaseOrders".
	Constructor string
	// TableVar is the variable holding the entity's *model.Table.
	TableVar string
	// SoftDeletes adds the six methods that only mean something on a table
	// whose spec sets SoftDeletes.
	SoftDeletes bool
}

// Query is the generated type: PurchaseOrderQuery.
func (s QuerySpec) Query() string { return s.Entity + "Query" }

// Collection is the generated slice type: PurchaseOrderCollection.
func (s QuerySpec) Collection() string { return s.Entity + "Collection" }

// Of is the unexported conversion from one model.Entity: purchaseOrderOf. It
// carries the entity because every entity of the package shares the scope.
func (s QuerySpec) Of() string { return lowerFirst(s.Entity) + "Of" }

// Column is the unexported adapter that turns a closure over the typed query
// into the one the core builder groups with: purchaseOrderColumn.
func (s QuerySpec) Column() string { return lowerFirst(s.Entity) + "Column" }

// Header is the first line of the file.
func (s QuerySpec) Header() string { return QueryHeader(s.Source) }

// Path is the file name, beside the entity's file.
func (s QuerySpec) Path() string { return s.Query() + ".go" }

// Validate reports what would make the rendered file not compile.
func (s QuerySpec) Validate() error {
	for _, name := range []struct{ what, value string }{
		{"entity", s.Entity}, {"constructor", s.Constructor},
	} {
		if !IsExportedIdentifier(name.value) {
			return fmt.Errorf("%s %q is not an exported Go identifier", name.what, name.value)
		}
	}
	if !isGoIdentifier(s.Package) || !isGoIdentifier(s.TableVar) {
		return fmt.Errorf("package %q and table variable %q have to be Go identifiers", s.Package, s.TableVar)
	}
	if s.Source == "" {
		return fmt.Errorf("the file declaring %s is required, for the header", s.Entity)
	}
	return nil
}

// QuerySpec is the query file of the module's entity, in app/Models.
func (m Module) QuerySpec() QuerySpec {
	return QuerySpec{
		Package:     "models",
		Entity:      m.Entity(),
		Source:      m.Entity() + ".go",
		Constructor: m.Constructor(),
		TableVar:    m.TableVar(),
	}
}

// RenderQuery produces <Entity>Query.go: the constructor, the typed query, the
// collection and the typed Fresh and Replicate of one entity.
//
// Every method is a forward of one to three lines to the core builder, and none
// has a type parameter. That is the point of generating it: a generic type in
// the API another package sees is compiled again inside each package that sees
// it, and a concrete one is compiled once, here.
func RenderQuery(s QuerySpec) ([]byte, error) {
	if err := s.Validate(); err != nil {
		return nil, err
	}
	return render(s.Path(), queryTemplate, s)
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func isGoIdentifier(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		letter := r == '_' || ('a' <= r && r <= 'z') || ('A' <= r && r <= 'Z')
		if !letter && (i == 0 || r < '0' || r > '9') {
			return false
		}
	}
	return true
}


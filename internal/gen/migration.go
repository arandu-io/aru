package gen

import (
	"fmt"
	"path/filepath"
)

// MigrationSpec is one migration file, independent of what asked for it.
//
// `aru make:module`, `aru make:model --migration` and `aru make:migration` all
// render through this: three commands, one shape of file. A second template
// would drift on the first change nobody remembered to make twice (RULE 9).
type MigrationSpec struct {
	// ID is the immutable identifier: "2026_08_07_000002_add_status_to_invoices".
	ID string
	// Var is the package-level value the migration is bound to. It is unexported:
	// nothing outside database/migrations names it.
	Var string
	// Table is the table the migration is about.
	Table string
	// Tenant composes the unique constraints and the index with tenant_id.
	Tenant bool
	// Fields are the columns.
	Fields []Field
	// Create picks the template: CREATE TABLE when true, ALTER TABLE ... ADD
	// COLUMN when false.
	Create bool
}

// UniqueFields returns the columns declared unique.
func (s MigrationSpec) UniqueFields() []Field {
	var out []Field
	for _, f := range s.Fields {
		if f.Unique {
			out = append(out, f)
		}
	}
	return out
}

// Path is where the file goes, which the id already decides.
func (s MigrationSpec) Path() string {
	return filepath.Join("database", "migrations", s.ID+".go")
}

// Validate reports what is wrong with the specification before a file is
// written. A specification error must never become broken code.
func (s MigrationSpec) Validate() error {
	if s.ID == "" || s.Var == "" || s.Table == "" {
		return fmt.Errorf("a migration needs an id, a variable name and a table")
	}
	if len(s.Fields) == 0 {
		return fmt.Errorf("a migration with no columns applies nothing and is still recorded as applied (RULE 16)")
	}
	seen := map[string]bool{}
	for _, f := range s.Fields {
		if !isIdentifier(f.Name) {
			return fmt.Errorf("column %q must be lowercase letters, digits and underscore, starting with a letter", f.Name)
		}
		if seen[f.Name] {
			return fmt.Errorf("column %q declared twice", f.Name)
		}
		seen[f.Name] = true
		if _, ok := types[f.Type]; !ok {
			return fmt.Errorf("column %q: unknown type %q (%s)", f.Name, f.Type, TypeList())
		}
	}
	return nil
}

// MigrationSpec is how a module describes its own create-table migration.
func (m Module) MigrationSpec() MigrationSpec {
	return MigrationSpec{
		ID:     m.MigrationID(),
		Var:    m.MigrationVar(),
		Table:  m.Table(),
		Tenant: m.Tenant,
		Fields: m.Fields,
		Create: true,
	}
}

// RenderMigration produces the file. Create picks the template.
func RenderMigration(s MigrationSpec) (File, error) {
	if err := s.Validate(); err != nil {
		return File{}, err
	}
	tmpl := migrationAlterTemplate
	if s.Create {
		tmpl = migrationCreateTemplate
	}
	content, err := render(s.ID+".go", tmpl, s)
	if err != nil {
		return File{}, err
	}
	return File{Path: s.Path(), Content: content}, nil
}

const migrationCreateTemplate = `package migrations

import "github.com/arandu-io/framework/kernel"

// {{.Var}} creates the {{.Table}} table.
//
// It is unexported and listed in All(), which is what the kernel collects: a
// migration nobody lists is a migration nobody applies, and the compiler says so
// here rather than the schema saying so in production.
//
// A migration is immutable once published. Changing this one changes nothing on
// a database that already applied it, and leaves two schemas in the world under
// one id -- alter it with a new migration instead (RULE 16).
//
// Every type below spells the same in SQLite, PostgreSQL and MySQL, so one
// schema serves all three. Anything a key or an index names is VARCHAR rather
// than TEXT, because MySQL refuses TEXT in a key without a prefix length. The id
// is generated by the application: gen_random_uuid, UUID() and randomblob are
// three spellings of one idea.
var {{.Var}} = kernel.Migration{
	ID: "{{.ID}}",
	Up: ` + "`" + `CREATE TABLE {{.Table}} (
		id         VARCHAR(255) PRIMARY KEY,
{{- if .Tenant}}
		tenant_id  VARCHAR(255) NOT NULL,
{{- end}}
{{- range .Fields}}
		{{.Column}}{{"\t"}}{{.SQLType}}{{if .Required}} NOT NULL{{end}},
{{- end}}
		created_at TIMESTAMP NOT NULL
{{- range .UniqueFields}},
		UNIQUE ({{if $.Tenant}}tenant_id, {{end}}{{.Column}})
{{- end}}
	);
{{- if .Tenant}}
	CREATE INDEX {{.Table}}_tenant_created_idx ON {{.Table}} (tenant_id, created_at, id);
{{- else}}
	CREATE INDEX {{.Table}}_created_idx ON {{.Table}} (created_at, id);
{{- end}}` + "`" + `,
	Down: ` + "`" + `DROP TABLE {{.Table}};` + "`" + `,
}
`

const migrationAlterTemplate = `package migrations

import "github.com/arandu-io/framework/kernel"

// {{.Var}} adds columns to the {{.Table}} table.
//
// It is unexported and listed in All(), which is what the kernel collects. A
// migration nobody lists is a migration nobody applies, and nothing anywhere
// fails: Go does not report an unused package-level variable, so the schema is
// simply never changed.
//
// Every column is added nullable, with no NOT NULL. During a rollout the
// previous binary is still inserting rows and knows nothing about these columns,
// so a NOT NULL without a default fails on its first insert -- and on every row
// already in the table. Backfill, then tighten it in a later migration (RULE 16).
//
// A migration is immutable once published. Changing this one after it has been
// applied anywhere leaves two schemas in the world under one id -- alter it with
// a new migration instead.
var {{.Var}} = kernel.Migration{
	ID: "{{.ID}}",
	Up: ` + "`" + `{{range .Fields}}ALTER TABLE {{$.Table}} ADD COLUMN {{.Column}} {{.SQLType}};
{{end}}{{range .UniqueFields}}CREATE UNIQUE INDEX {{$.Table}}_{{.Column}}_uidx ON {{$.Table}} ({{if $.Tenant}}tenant_id, {{end}}{{.Column}});
{{end}}` + "`" + `,
	// Dropping the column drops the index with it on all three engines, which is
	// why there is no DROP INDEX here: its spelling is the one thing SQLite,
	// PostgreSQL and MySQL do not agree about.
	Down: ` + "`" + `{{range .Fields}}ALTER TABLE {{$.Table}} DROP COLUMN {{.Column}};
{{end}}` + "`" + `,
}
`

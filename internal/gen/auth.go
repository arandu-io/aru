const authModuleTemplate = `// Package authui holds the sign-in screens.
//
// Generated by ` + "`aru make:auth`" + `, and yours from this moment on: edit it, delete
// what you do not want, restyle it. Nothing in the framework imports it back.
//
// The authentication itself stays in the framework's auth module -- password
// verification, the timing-equalized failure path, session rotation. This package
// owns what a screen owns, which is the markup and the two handlers that drive it.
package authui

import (
	"github.com/arandu-io/framework/httpx"
	"github.com/arandu-io/framework/kernel"
	"github.com/arandu-io/framework/modules/auth"
	"github.com/arandu-io/framework/security"
)

// Module registers the screens.
type Module struct {
	auth     *auth.Service
	sessions *security.SessionStore
	csrf     *security.CSRF
	tenant   auth.TenantResolver
}

// New returns the module.
//
// Register it INSTEAD of auth.New: both answer /auth/login, and this is the one
// with a real page. Registering both would give the same path two handlers.
//
// The session store and the CSRF issuer are passed in rather than reached
// through the service, because a screen is allowed to know about a token and a
// cookie, and the service is not allowed to expose its own dependencies.
func New(svc *auth.Service, sessions *security.SessionStore, csrf *security.CSRF, tenant auth.TenantResolver) *Module {
	if tenant == nil {
		tenant = auth.FixedTenant("")
	}
	return &Module{auth: svc, sessions: sessions, csrf: csrf, tenant: tenant}
}

// Compile-time proof that the module honors the contract it claims.
var _ kernel.Module = (*Module)(nil)

// Name is the module identifier.
func (m *Module) Name() string { return "authui" }

// Routes registers the screens.
//
// There are no migrations here: the users table belongs to the framework's auth
// module, and two modules migrating one table is how a schema ends up with two
// owners.
func (m *Module) Routes(r *httpx.Router) {
	g := r.Group("/auth")
	g.Get("/login", m.showLogin)
	g.Post("/login", m.doLogin)
	g.Post("/logout", m.doLogout)

	// arandu:begin custom
	// Registration, password reset and anything else you add go here.
	// arandu:end custom
}
`

const authHandlersTemplate = `package authui

import (
	"errors"
	"net/http"

	"github.com/arandu-io/framework/modules/auth"
	"github.com/arandu-io/framework/observability"
	"github.com/arandu-io/framework/validation"
	"github.com/arandu-io/framework/view"

	"{{.ModulePath}}/resources/views"
)

// Handlers are thin on purpose: extract the input, delegate to the service,
// render. No business rule and no repository access lives here -- ` + "`aru doctor`" + `
// complains when a handler imports the data package.

// showLogin renders the form with a fresh CSRF token.
func (m *Module) showLogin(w http.ResponseWriter, r *http.Request) {
	token, err := m.csrf.Issue(m.sessions.IDFromRequest(r))
	if err != nil {
		observability.Log(r.Context()).Error("issuing csrf token", "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)
		return
	}

	// The renderer sets the content type and records the render on the
	// puts the render on the request timeline. Calling Render directly leaves
	// the template column at zero, which says the view is free when nobody
	// measured it.
	data := views.AuthPage{
		AppName:  "{{.ModulePath}}",
		Title:    "Sign in",
		Token:    token,
		LoginURL: "/auth/login",
	}
	if err := view.NewRenderer().Render(r.Context(), w, http.StatusOK, "auth.login", data); err != nil {
		observability.Log(r.Context()).Error("rendering the sign-in page", "error", err)
	}
}

// doLogin authenticates and rotates the session.
//
// On failure it re-renders the form with the message inline, which is the whole
// shape of validation on this stack: the server rejects, and the same response
// carries the reason. Nothing is validated twice in the browser.
func (m *Module) doLogin(w http.ResponseWriter, r *http.Request) {
	in := auth.LoginRequest{
		Email:    r.PostFormValue("email"),
		Password: r.PostFormValue("password"),
	}
	if errs := in.Validate(); errs.Any() {
		m.rejected(w, r, in.Email, errs, http.StatusUnprocessableEntity)
		return
	}

	// The tenant comes from the application, never from the request: a form
	// field here would let anyone pick which tenant to authenticate against.
	u, err := m.auth.Authenticate(r.Context(), m.tenant(r), in.Email, in.Password)
	if err != nil {
		if errors.Is(err, auth.ErrInvalidCredentials) {
			// One message for both halves. Saying which one was wrong turns this
			// endpoint into an account enumeration oracle.
			m.rejected(w, r, in.Email, validation.Errors{
				"email": {"invalid email or password"},
			}, http.StatusUnauthorized)
			return
		}
		observability.Log(r.Context()).Error("login failed", "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)
		return
	}

	// Rotating the id is mandatory here: keeping the pre-login session is
	// session fixation, and ` + "`aru doctor`" + ` checks that this call exists.
	old := m.sessions.IDFromRequest(r)
	if _, err := m.sessions.Rotate(r.Context(), w, old, auth.SubjectOf(u)); err != nil {
		observability.Log(r.Context()).Error("starting session", "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)
		return
	}

	// HX-Redirect makes HTMX navigate without a full page reload.
	w.Header().Set("HX-Redirect", "/")
	w.WriteHeader(http.StatusOK)
}

// doLogout destroys the session on the server, not only in the browser.
func (m *Module) doLogout(w http.ResponseWriter, r *http.Request) {
	if err := m.sessions.Destroy(r.Context(), w, m.sessions.IDFromRequest(r)); err != nil {
		observability.Log(r.Context()).Error("destroying session", "error", err)
	}
	w.Header().Set("HX-Redirect", "/auth/login")
	w.WriteHeader(http.StatusOK)
}

// rejected re-renders just the form, which is what HTMX swaps back in.
//
// The token is reissued because the session id may have changed, and the email
// is kept because retyping it after a rejection is the fastest way to make a
// login screen unpleasant. The password never comes back.
func (m *Module) rejected(w http.ResponseWriter, r *http.Request, email string, errs validation.Errors, status int) {
	token, err := m.csrf.Issue(m.sessions.IDFromRequest(r))
	if err != nil {
		observability.Log(r.Context()).Error("issuing csrf token", "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)
		return
	}

	// The status is explicit: HTMX swaps the body of a 422 and of a 200 alike,
	// so answering 200 for a rejection would make the browser, the logs and
	// every metric agree that it worked.
	form := views.AuthPage{
		AppName:    "{{.ModulePath}}",
		Title:      "Sign in",
		Token:      token,
		LoginURL:   "/auth/login",
		Email:      email,
		EmailError: errs.First(),
	}
	if err := view.NewRenderer().Render(r.Context(), w, status, "auth.login", form); err != nil {
		observability.Log(r.Context()).Error("rendering the form", "error", err)
	}
}

// arandu:begin custom
// Your own handlers go here.
// arandu:end custom
`

// The views are no longer here. `aru make:auth` writes the nine of
// `laravel/ui` in resources/views, as kyse — see authviews.go and ADR 0022.

// authHomeControllerTemplate is the HomeController the kit publishes, the same
// file `php artisan ui bootstrap --auth` generates.
//
// The constructor keeps the skeleton's signature -- NewHomeController(appName)
// -- because make:auth does not edit bootstrap/app.go. A different signature
// would break the wiring the project already has, in a file the command never
// touches and the reader has no reason to suspect.
const authHomeControllerTemplate = `package controllers

import (
	"github.com/arandu-io/framework/httpx"

	"{{ .ModulePath }}/resources/views"
)

// HomeController answers the landing page.
//
// It renders with views.AuthPage, the struct layouts/app declares: a page
// renders with its layout's type, so every screen sharing this layout shares
// this struct. A field this page does not use stays at its zero value.
type HomeController struct {
	Controller

	// appName is what the page is titled. It arrives through the constructor
	// rather than through a global read: a controller that reads the
	// environment is a controller no test can pin.
	appName string
}

// NewHomeController returns the controller. bootstrap/app.go builds it and hands
// it to the routes.
func NewHomeController(appName string) *HomeController {
	return &HomeController{appName: appName}
}

// Compile-time proof that this controller answers GET / the way Resource and the
// route table expect. It costs nothing and catches a renamed method.
var _ httpx.Indexer = (*HomeController)(nil)

// Index renders the landing page.
func (c *HomeController) Index(ctx *httpx.Context) error {
	// arandu:begin custom
	return ctx.View("home", views.AuthPage{
		AppName: c.appName,
		Title:   c.appName,
		HomeURL: "/",

		// The navigation draws a link only for what answers. The kit ships the
		// sign-in handler and nothing else, so registration and password reset
		// stay off until you write them -- a link to a route nobody registered
		// is a 404 the layout put there.
		LoginURL:         "/auth/login",
		LogoutURL:        "/auth/logout",
		HasRegister:      false,
		HasPasswordReset: false,
	})
	// arandu:end custom
}
`
